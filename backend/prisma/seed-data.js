function slugify(...parts) {
  return parts
    .filter(Boolean)
    .flatMap((part) =>
      String(part)
        .toLowerCase()
        .normalize('NFKD')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '')
        .split('-'),
    )
    .filter(Boolean)
    .join('-')
}

